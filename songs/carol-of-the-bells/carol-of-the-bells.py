"""Leontovych, Shchedryk ("Carol of the Bells", 1916): our FM bell arrangement.

carol-of-the-bells.mid is generated by build_carol.py, which holds
Leontovych's four voices and our arrangement of them for eight FM-1 parts:

    .venv/bin/python songs/carol-of-the-bells/build_carol.py --bpm 168

The idea: the DX7 family is famous for bells, so the four-note ostinato
rings on bells throughout, the inner voices come in on mallets, a choir
joins the second time round with octave doublings above and below, and a
low bell tolls each phrase.

On the FM-1: Voice1-8 on MIDI Ch 1-8, Effect Ch 16, song bank loaded.
"""

from fm1.song import Part, Reverb, Song

# Stereo seating, applied only by `song carol-of-the-bells --record FILE
# --stems` (the FM-1 ignores MIDI pan): the ostinato bells left of centre and
# their descant right, alto mallets left and tenor right, pad, bass and the
# big bell near the middle.
SONG = Song(
    title="Carol of the Bells (Shchedryk)",
    parts=[
        # Ostinato: CELESTE and BELL 1 were the picks of seven bells.
        Part(channel=1, sound="rom1b:7", tracks=["Ostinato"], pan=-0.25),     # CELESTE
        Part(channel=2, sound="bells:1", tracks=["Descant"], pan=0.35),       # BELL 1
        Part(channel=3, sound="int:3", tracks=["Alto"], pan=-0.55),           # VIBE 1
        Part(channel=4, sound="rom3a:7", tracks=["Tenor"], velocity=1.5,      # MARIMBA;
             pan=0.55),                                                       # "too quiet"
        # The "choir" part: WARM PAD 1, picked from six choirs and pads (F. CHOIR
        # "sucks"). Its transpose byte is -24 against carriers at 2x, so +12.
        Part(channel=5, sound="ortega16:19", tracks=["Choir"], transpose=12),  # WARM PAD 1
        # Bass: pizzicato strings, STR.PIZZ.1, picked from five (ORCH-CHIME
        # "sucks worse").
        Part(channel=6, sound="dxoc09:29", tracks=["Bass"], pan=0.15),        # STR.PIZZ.1
        # Strings under the bass the second time, at the bass's own pitch (an
        # octave below was "not good"). VIOLA SECN, picked from three (STRINGS 2
        # "sucks"); its transpose byte is -24 against carriers at 2x, so +12.
        Part(channel=7, sound="bank0043:15", tracks=["Pedal"], transpose=12,
             pan=-0.15),                                                      # VIOLA SECN
        Part(channel=8, sound="b1:31", tracks=["Tolling bell"], pan=0.2),     # TUB BELLS
    ],
    reverb=Reverb("hall", decay=40, mix=12),
)
